#!/usr/bin/env node
// Writes docs/research/TOPIC_RANKING.md from docs/research/data/engineering-topics.json (roadmap W7).
// Usage: node local/topic-ranking.mjs [--print]
import { readFileSync, writeFileSync } from "node:fs";
import { rankTopics, rankingMarkdown, TOPIC_WEIGHTS } from "../engine/src/topic-score.mjs";

const root = new URL("../", import.meta.url);
const data = JSON.parse(readFileSync(new URL("docs/research/data/engineering-topics.json", root), "utf8"));
const prior = JSON.parse(readFileSync(new URL("engine/data/reference-prior.json", root), "utf8"));
const ranked = rankTopics(data.topics, { pastFilms: data.pastFilms, prior });
const weights = Object.entries(TOPIC_WEIGHTS).map(([k, w]) => `${k} ${Math.round(w * 100)}%`).join(", ");
const rejected = ranked.filter((s) => s.rejected.length).map((s) => `- ${s.title}: ${s.rejected.map((r) => r.why).join("; ")}.`);
const md = `# Topic ranking (W7)

Generated by \`node local/topic-ranking.mjs\` from \`docs/research/data/engineering-topics.json\` with \`engine/src/topic-score.mjs\`. Do not edit by hand.

**Read this first.** The total ranks topics against each other; it does not predict views. Factor values (0-5, 5 = better for Zupona) are a reading of the market study, not measurements; each has a reason in the JSON. Weak-evidence topics lose 10%. Visual and source claims still need the W10 archive check before a film starts.

Weights: ${weights}.

${rankingMarkdown(ranked)}

Columns: Dem demand, Out outlier evidence, Comp competition (5 = little), US appeal, Vis authentic free visuals, Rel source reliability, Ads advertiser fit, Eff effort (5 = low), Ever evergreen, Story narrative, New unlike past films (computed).

## Rejected
${rejected.length ? rejected.join("\n") : "- none"}
`;
if (process.argv.includes("--print")) process.stdout.write(md);
else writeFileSync(new URL("docs/research/TOPIC_RANKING.md", root), md);

#!/usr/bin/env node
/**
 * Writes engine/src/role-craft.mjs: the lines of prompts/4 (the squad runtime prompts) that the
 * voiceover film run sends to the free brain, copied word for word, grouped by role and stage.
 *   node local/role-craft-build.mjs          write the module
 *   node local/role-craft-build.mjs --check  fail when the module is out of date with prompts/4
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = readFileSync(join(ROOT, "prompts/4-zupona-squad-brains.txt"), "utf8");
const OUT = join(ROOT, "engine/src/role-craft.mjs");

/** squad number in prompts/4 -> its text */
const squads = new Map(SRC.split(/^##### (\d+)\. .*#####$/m).slice(1).reduce((acc, v, i, a) => (i % 2 === 0 ? [...acc, [Number(v), a[i + 1]]] : acc), /** @type {[number, string][]} */ ([])));
/** @param {number} n @param {string} prefix */
function line(n, prefix) {
  const hits = (squads.get(n) ?? "").split("\n").filter((l) => l.startsWith(prefix));
  if (hits.length !== 1) throw new Error(`prompts/4 squad ${n}: ${hits.length} lines start with "${prefix}"`);
  return hits[0].trimEnd();
}

/** role id -> { stage, squad, title, lines } ; stage V3 director, V4 picture plan, V5 edit director */
const SPEC = [
  { id: "cinematography-visual-director", stage: "V3", squad: 1, title: "Visual Director (Media Hunters: Slot Interpreter, Literalness Judge)", prefixes: ["- Evidence slots are literal", "- Illustrative slots are on-mood", "- Negative-context slots never get", "- Expert panel: before ranking"] },
  { id: "story-opening-hook", stage: "V3", squad: 4, title: "Hook Writer (Viral Story Builders)", prefixes: ["Hook (first 30 s)", "- Real reversals from the record", "- But/therefore causality"] },
  { id: "editing-pace", stage: "V3", squad: 7, title: "Cadence Designer and Beat Scheduler (Timeline Composers)", prefixes: ["- Hook 15-30 events per minute", "- A pattern interrupt about every 25 s", "- A reset about every 3 min", "- Restraint before reveals"] },
  { id: "animation-motion-director", stage: "V4", squad: 5, title: "Parallax and Ken Burns Designer, Kinetic Type Designer (Visual Enhancers)", prefixes: ["- Panel: a colourist, a motion designer", "- Ask of every treatment", "- Restraint is quality", "- FX-MAP", "- FX-ARCHIVE", "- FX-KINETIC", "- FX-FILM", "- Never replicas of real newspapers", "- Accessibility: text contrast"] },
  { id: "color-look-dev", stage: "V4", squad: 5, title: "Colourist and Archive Restorer (Visual Enhancers)", prefixes: ["- Archive treatment only on archive", "- Look token applied", "- Shot-to-shot colour delta"] },
  { id: "footage-asset-strategist", stage: "V4", squad: 1, title: "Query Engineer and Public-Domain Archivist (Media Hunters)", prefixes: ["- Commons: proper noun", "- Government and museum sources", "- Openverse:", "- Pexels, Pixabay, Mixkit", "- Editorial and archives"] },
  { id: "cinematography-archive-language", stage: "V4", squad: 1, title: "Literalness Judge (Media Hunters)", prefixes: ["- Evidence slots are literal", "- Illustrative slots are on-mood", "- Negative-context slots never get", "- Brands, logos and products"] },
  { id: "editing-cut-logic", stage: "V5", squad: 7, title: "Transition and Edit-Grammar Designer (Timeline Composers)", prefixes: ["- Panel: a feature documentary editor", "- Of every cut", "- Restraint before reveals", "- Vary shot size; keep screen direction", "- J-cuts and L-cuts at resets", "- Default transition is the straight cut"] },
  { id: "audience-retention", stage: "V5", squad: 7, title: "Cadence Designer, Beat Scheduler (Timeline Composers)", prefixes: ["- Hook 15-30 events per minute", "- A pattern interrupt about every 25 s", "- A reset about every 3 min", "- Anchor visual lands", "- Spoken numbers appear on screen", "- Nothing appears before it is named", "- 1-2 beats of VO and music out"] },
].map((s) => ({ id: s.id, stage: s.stage, squad: s.squad, title: s.title, lines: s.prefixes.map((p) => line(s.squad === 7 && p.startsWith("- Restraint") ? 7 : s.squad, p)) }));

const header = `/**
 * Role craft: the strong instructions of the squad runtime prompts (prompts/4-zupona-squad-brains.txt) that
 * the voiceover film run sends to the free brain. GENERATED by local/role-craft-build.mjs, word for word from
 * prompts/4 (a test fails when they drift). Before this module no code read prompts/4 at all
 * (docs/AGENT_AUDIT.md). The brain is asked in three passes (V3 director, V4 picture plan, V5 edit director);
 * each pass gets only the roles it can act on, so the prompt stays far under Groq's 7,200-token limit.
 */
`;
const body = `export const ROLE_CRAFT = Object.freeze(${JSON.stringify(SPEC, null, 1)});

/** @param {"V3" | "V4" | "V5"} stage the roles whose instructions that pass sends. */
export function roleCraftRoles(stage) {
  return ROLE_CRAFT.filter((r) => r.stage === stage);
}

/**
 * The roles' own words for one pass, de-duplicated, as one prompt block.
 * @param {"V3" | "V4" | "V5"} stage
 */
export function roleCraft(stage) {
  const seen = new Set();
  const out = ["ROLE CRAFT (the squad desks' own standing orders; they apply on top of the rules above):"];
  for (const r of roleCraftRoles(stage)) {
    const fresh = r.lines.filter((l) => !seen.has(l));
    for (const l of fresh) seen.add(l);
    if (fresh.length) out.push(\`[\${r.title}]\`, ...fresh);
  }
  return out.join("\\n");
}
`;
const text = header + body;
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) { console.error("engine/src/role-craft.mjs is out of date: run node local/role-craft-build.mjs"); process.exit(1); }
} else writeFileSync(OUT, text);
